async function printSheet(source:HTMLElement,title:string,locale:Locale) {
  const win=window.open('','_blank','width=1200,height=850');
  if(!win) throw Error(locale==='fr'?'Autorisez la fenêtre d’impression pour enregistrer le PDF.':'Allow the print window to save the PDF.');
  win.document.open();win.document.write('<!doctype html><html><head><meta charset="utf-8"></head><body></body></html>');win.document.close();
  win.document.documentElement.lang=locale;win.document.title=title;
  const base=win.document.createElement('base');base.href=location.origin+'/';win.document.head.append(base);
  const style=win.document.createElement('style');style.textContent=printStyles;win.document.head.append(style);
  // Embed images before moving the document to the print window. This also
  // keeps signed logo URLs from expiring while the print dialog stays open.
  const content=source.cloneNode(true) as HTMLElement;
  const images=new Map<string,Promise<string|null>>();
  await Promise.all(Array.from(content.querySelectorAll('img')).map(async img=>{
    if(img.hidden||img.src.startsWith('data:'))return;
    if(!images.has(img.src))images.set(img.src,(async()=>{
      try{
        const response=await fetch(img.src,{signal:AbortSignal.timeout(8000)});
        if(!response.ok)return null;
        const blob=await response.blob();
        return await new Promise<string>((resolve,reject)=>{const reader=new FileReader();reader.onload=()=>resolve(String(reader.result));reader.onerror=()=>reject(reader.error);reader.readAsDataURL(blob);});
      }catch{return null;}
    })());
    const data=await images.get(img.src);if(data)img.src=data;else img.hidden=true;
  }));
  win.document.body.append(win.document.importNode(content,true));
  await Promise.all(Array.from(win.document.images).filter(img=>!img.hidden).map(img=>img.decode().catch(()=>{img.hidden=true;})));
  await win.document.fonts.ready;
  win.opener=null;win.focus();win.print();
}

export function PresentationDrawDialog({initial,locale,onClose}:{initial:PresentationDraw;locale:Locale;onClose:()=>void}) {
  const [data,setData]=useState(initial),[busy,setBusy]=useState(false),[error,setError]=useState('');
  const text=(a:string,b:string)=>locale==='fr'?a:b;
  async function choose(source:'published'|'generated') {
    setBusy(true);setError('');
    try{setData(await getPresentationDraw(data.block.id,source));}catch{setError(text('Impossible de charger cette version de l’ordre.','Unable to load this draw version.'));}finally{setBusy(false);}
  }
  return <ModalDialog className="presentation-draw-modal" eyebrow="PDF" title={text('Draw de présentation','Presentation draw')} description={data.block.name} onClose={onClose}>
    <div className="presentation-draw-tools">
      <label>{text('Version de l’ordre','Draw version')}<select value={data.source} disabled={busy} onChange={e=>void choose(e.target.value as 'published'|'generated')}>
        {data.published_version?<option value="published">{text('Ordre publié','Published draw')} v{data.published_version}</option>:null}
        {data.generated_version!==data.published_version?<option value="generated">{text('Ordre généré - brouillon','Generated draw - draft')} v{data.generated_version}</option>:null}
      </select></label>
      <button className="primary-button" type="button" disabled={busy} onClick={()=>{const sheet=document.querySelector<HTMLElement>('.presentation-draw-sheet');if(sheet)void printSheet(sheet,`${data.show_name} - ${data.block.name} - ${text('Draw de présentation','Presentation draw')} v${data.version}`,locale).catch(e=>setError(e.message));}}><FileDown size={16}/>{text('Imprimer ou enregistrer en PDF','Print or save as PDF')}</button>
    </div>
    {data.generated_version!==data.published_version&&data.published_version?<p>{text('Une version générée plus récente attend sa publication. Le document utilise la version choisie ci-dessus.','A newer generated version awaits publication. This document uses the version selected above.')}</p>:null}
    {error?<p role="alert">{error}</p>:null}
    <div className="presentation-draw-preview"><PresentationDrawSheet data={data} locale={locale}/></div>
  </ModalDialog>;
}
